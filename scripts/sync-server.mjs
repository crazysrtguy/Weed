// Copies the shared rule modules into the edge function so the server runs the exact same engine as the client.
// Also generates the server's pay-config from devnet-config.json (prices and treasury come from ONE file).
import {copyFileSync,mkdirSync,readFileSync,writeFileSync} from 'node:fs';
mkdirSync('supabase/functions/_shared',{recursive:true});
for(const f of ['engine.mjs','league.mjs','server-core.mjs','chain.mjs'])copyFileSync(f,`supabase/functions/_shared/${f}`);
const c=JSON.parse(readFileSync('devnet-config.json','utf8'));
const items=Object.fromEntries(Object.keys(c.itemsToken).map(k=>[k,{token:c.itemsToken[k],sol:c.itemsSol[k]}]));
const cfg={cluster:c.cluster,symbol:c.symbol,decimals:c.decimals,mint:c.mint,treasuryOwner:c.treasuryOwner,items};
writeFileSync('supabase/functions/_shared/pay-config.mjs',`// GENERATED by scripts/sync-server.mjs from devnet-config.json. Do not edit.
export const PAY_CONFIG=${JSON.stringify(cfg,null,1)};
`);
console.log('synced engine, league, server-core, chain and pay-config to supabase/functions/_shared');
